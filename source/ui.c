void ui_init(void) {}

void ui_rect(float x, float y, float w, float h, u32 c) {
    if (w <= 0 || h <= 0) return;
    C2D_DrawRectSolid(x, y, 0.5f, w, h, c);
}

void ui_frame(float x, float y, float w, float h, int t, u32 c) {
    ui_rect(x, y, w, t, c);
    ui_rect(x, y + h - t, w, t, c);
    ui_rect(x, y + t, t, h - 2 * t, c);
    ui_rect(x + w - t, y + t, t, h - 2 * t, c);
}

void ui_bevel(float x, float y, float w, float h, u32 face, u32 hi, u32 lo) {
    ui_rect(x, y, w, h, lo);
    ui_rect(x, y, w - 2, h - 2, hi);
    ui_rect(x + 2, y + 2, w - 4, h - 4, face);
}

int ui_text_w(const char *s, int scale) {
    int n = (int)strlen(s);
    if (!n) return 0;
    return n * 6 * scale - scale;
}

void ui_text_clip(float x, float y, const char *s, int sc, u32 c, float cx0, float cx1) {
    float px = x;
    for (; *s; s++) {
        unsigned char ch = (unsigned char)*s;
        if (ch < 32 || ch > 126) ch = '?';
        if (px > cx1) break;
        if (px + 5 * sc >= cx0 && ch != ' ') {
            const u8 *g = font5x7[ch - 32];
            for (int r = 0; r < 8; r++) {
                int col = 0;
                while (col < 5) {
                    if ((g[col] >> r) & 1) {
                        int st = col;
                        while (col < 5 && ((g[col] >> r) & 1)) col++;
                        float rx = px + st * sc, rw = (float)(col - st) * sc;
                        if (rx < cx0) { rw -= cx0 - rx; rx = cx0; }
                        if (rx + rw > cx1) rw = cx1 - rx;
                        if (rw > 0) ui_rect(rx, y + r * sc, rw, sc, c);
                    } else col++;
                }
            }
        }
        px += 6 * sc;
    }
}

void ui_text(float x, float y, const char *s, int scale, u32 c) {
    ui_text_clip(x, y, s, scale, c, -10000.f, 10000.f);
}

void ui_text_shadow(float x, float y, const char *s, int scale, u32 c, u32 sh) {
    ui_text(x + scale, y + scale, s, scale, sh);
    ui_text(x, y, s, scale, c);
}

void ui_text_center(float cx, float y, const char *s, int scale, u32 c) {
    ui_text(cx - ui_text_w(s, scale) / 2.0f, y, s, scale, c);
}

void ui_icon(Icon ic, float x, float y, int sc, u32 c, bool mirror) {
    if (ic < 0 || ic >= IC_COUNT) return;
    for (int r = 0; r < 11; r++) {
        const char *row = icons[ic][r];
        int col = 0;
        while (col < 11) {
            int cc = mirror ? 10 - col : col;
            if (row[cc] == '#') {
                int st = col;
                while (col < 11 && row[mirror ? 10 - col : col] == '#') col++;
                ui_rect(x + st * sc, y + r * sc, (float)(col - st) * sc, sc, c);
            } else col++;
        }
    }
}

u32 ui_alpha(u32 c, float a) {
    if (a < 0) a = 0;
    if (a > 1) a = 1;
    u32 al = (u32)(((c >> 24) & 0xFF) * a);
    return (c & 0x00FFFFFF) | (al << 24);
}

u32 ui_mix(u32 a, u32 b, float t) {
    if (t < 0) t = 0;
    if (t > 1) t = 1;
    u32 out = 0;
    for (int i = 0; i < 4; i++) {
        float ca = (float)((a >> (i * 8)) & 0xFF), cb = (float)((b >> (i * 8)) & 0xFF);
        u32 v = (u32)(ca + (cb - ca) * t);
        out |= (v & 0xFF) << (i * 8);
    }
    return out;
}
